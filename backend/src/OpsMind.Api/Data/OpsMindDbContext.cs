using Microsoft.EntityFrameworkCore;
using OpsMind.Api.Auth;
using OpsMind.Api.Domain;

namespace OpsMind.Api.Data;

public class OpsMindDbContext : DbContext
{
    private readonly ICurrentUser _currentUser;

    public OpsMindDbContext(DbContextOptions<OpsMindDbContext> options, ICurrentUser currentUser)
        : base(options)
    {
        _currentUser = currentUser;
    }

    /// <summary>Read by the global query filters. Guid.Empty matches nothing, so anonymous requests see no tenant data.</summary>
    public Guid CurrentOrganisationId => _currentUser.OrganisationId ?? Guid.Empty;

    public DbSet<Organisation> Organisations => Set<Organisation>();
    public DbSet<User> Users => Set<User>();
    public DbSet<Plant> Plants => Set<Plant>();
    public DbSet<ProductionLine> ProductionLines => Set<ProductionLine>();
    public DbSet<Shift> Shifts => Set<Shift>();
    public DbSet<EquipmentCategory> EquipmentCategories => Set<EquipmentCategory>();
    public DbSet<Equipment> EquipmentItems => Set<Equipment>();
    public DbSet<ProductionRecord> ProductionRecords => Set<ProductionRecord>();
    public DbSet<QualityRecord> QualityRecords => Set<QualityRecord>();
    public DbSet<DowntimeEvent> DowntimeEvents => Set<DowntimeEvent>();
    public DbSet<AuditLog> AuditLogs => Set<AuditLog>();

    protected override void OnModelCreating(ModelBuilder b)
    {
        b.Entity<Equipment>().ToTable("equipment");

        b.Entity<Organisation>(e => e.Property(x => x.Name).HasMaxLength(200));

        b.Entity<User>(e =>
        {
            e.Property(x => x.Role).HasConversion<string>();
        });

        b.Entity<Shift>(e =>
        {
            e.Property(x => x.DurationMinutes).HasComputedColumnSql("generated by database", stored: true);
        });

        b.Entity<Equipment>(e =>
        {
            e.Property(x => x.Status).HasConversion<string>();
            e.Property(x => x.IdealRatePerHour).HasPrecision(10, 2);
        });

        b.Entity<DowntimeEvent>(e =>
        {
            e.Property(x => x.Category).HasConversion<string>();
            e.Property(x => x.DurationMinutes).HasPrecision(12, 2).HasComputedColumnSql("generated by database", stored: true);
        });

        b.Entity<AuditLog>(e => e.Property(x => x.Details).HasColumnType("jsonb"));

        // Tenant isolation: every query on these sets is filtered by the caller's organisation.
        // Entities without an OrganisationId column are filtered through their parents.
        b.Entity<Organisation>().HasQueryFilter(o => o.Id == CurrentOrganisationId);
        b.Entity<User>().HasQueryFilter(u => u.OrganisationId == CurrentOrganisationId);
        b.Entity<Plant>().HasQueryFilter(p => p.OrganisationId == CurrentOrganisationId);
        b.Entity<EquipmentCategory>().HasQueryFilter(c => c.OrganisationId == CurrentOrganisationId);
        b.Entity<ProductionLine>().HasQueryFilter(l => l.Plant.OrganisationId == CurrentOrganisationId);
        b.Entity<Shift>().HasQueryFilter(s => s.Plant.OrganisationId == CurrentOrganisationId);
        b.Entity<Equipment>().HasQueryFilter(e => e.ProductionLine.Plant.OrganisationId == CurrentOrganisationId);
        b.Entity<ProductionRecord>().HasQueryFilter(p => p.Equipment.ProductionLine.Plant.OrganisationId == CurrentOrganisationId);
        b.Entity<QualityRecord>().HasQueryFilter(q => q.ProductionRecord.Equipment.ProductionLine.Plant.OrganisationId == CurrentOrganisationId);
        b.Entity<DowntimeEvent>().HasQueryFilter(d => d.Equipment.ProductionLine.Plant.OrganisationId == CurrentOrganisationId);
        b.Entity<AuditLog>().HasQueryFilter(a => a.OrganisationId == CurrentOrganisationId);

        // The database enforces RESTRICT everywhere except quality rows, which follow their production record.
        foreach (var foreignKey in b.Model.GetEntityTypes().SelectMany(t => t.GetForeignKeys()))
        {
            foreignKey.DeleteBehavior = DeleteBehavior.Restrict;
        }
        b.Entity<QualityRecord>().HasOne(q => q.ProductionRecord).WithOne(p => p.Quality)
            .HasForeignKey<QualityRecord>(q => q.ProductionRecordId).OnDelete(DeleteBehavior.Cascade);

        ApplySnakeCaseNames(b);
        ApplyTimestampDefaults(b);
    }

    private static void ApplySnakeCaseNames(ModelBuilder b)
    {
        foreach (var entityType in b.Model.GetEntityTypes())
        {
            entityType.SetTableName(ToSnakeCase(entityType.GetTableName()!));
            foreach (var property in entityType.GetProperties())
            {
                property.SetColumnName(ToSnakeCase(property.Name));
            }
        }
    }

    private static void ApplyTimestampDefaults(ModelBuilder b)
    {
        foreach (var entityType in b.Model.GetEntityTypes())
        {
            foreach (var name in new[] { nameof(Organisation.CreatedAt), nameof(Plant.UpdatedAt) })
            {
                var property = entityType.FindProperty(name);
                if (property is null) continue;
                property.SetDefaultValueSql("now()");
                property.ValueGenerated = Microsoft.EntityFrameworkCore.Metadata.ValueGenerated.OnAdd;
            }
        }
    }

    private static string ToSnakeCase(string name) =>
        string.Concat(name.Select((c, i) =>
            i > 0 && char.IsUpper(c) ? "_" + char.ToLowerInvariant(c) : char.ToLowerInvariant(c).ToString()));

    public override int SaveChanges(bool acceptAllChangesOnSuccess)
    {
        StampUpdatedAt();
        return base.SaveChanges(acceptAllChangesOnSuccess);
    }

    public override Task<int> SaveChangesAsync(bool acceptAllChangesOnSuccess, CancellationToken cancellationToken = default)
    {
        StampUpdatedAt();
        return base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken);
    }

    private void StampUpdatedAt()
    {
        var now = DateTime.UtcNow;
        foreach (var entry in ChangeTracker.Entries<IHasUpdatedAt>().Where(e => e.State == EntityState.Modified))
        {
            entry.Entity.UpdatedAt = now;
        }
    }
}
