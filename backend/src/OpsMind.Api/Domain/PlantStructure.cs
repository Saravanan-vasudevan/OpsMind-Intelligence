namespace OpsMind.Api.Domain;

public class Plant : IHasUpdatedAt
{
    public Guid Id { get; set; }
    public Guid OrganisationId { get; set; }
    public string Name { get; set; } = string.Empty;
    public string Code { get; set; } = string.Empty;
    public string? Location { get; set; }
    public string TimeZone { get; set; } = "UTC";
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }

    public ICollection<ProductionLine> Lines { get; set; } = new List<ProductionLine>();
    public ICollection<Shift> Shifts { get; set; } = new List<Shift>();
}

public class ProductionLine : IHasUpdatedAt
{
    public Guid Id { get; set; }
    public Guid PlantId { get; set; }
    public Plant Plant { get; set; } = null!;
    public string Name { get; set; } = string.Empty;
    public string Code { get; set; } = string.Empty;
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }

    public ICollection<Equipment> Equipment { get; set; } = new List<Equipment>();
}

public class Shift : IHasUpdatedAt
{
    public Guid Id { get; set; }
    public Guid PlantId { get; set; }
    public Plant Plant { get; set; } = null!;
    public string Name { get; set; } = string.Empty;
    public TimeOnly StartTime { get; set; }
    public TimeOnly EndTime { get; set; }

    /// <summary>Generated by the database; handles shifts that run past midnight.</summary>
    public int DurationMinutes { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }
}
