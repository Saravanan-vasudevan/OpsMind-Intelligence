namespace OpsMind.Api.Domain;

public class ProductionRecord : IHasUpdatedAt
{
    public Guid Id { get; set; }
    public Guid EquipmentId { get; set; }
    public Equipment Equipment { get; set; } = null!;
    public Guid ShiftId { get; set; }
    public Shift Shift { get; set; } = null!;
    public DateOnly ShiftDate { get; set; }
    public int UnitsProduced { get; set; }
    public int TargetUnits { get; set; }
    public int RunMinutes { get; set; }
    public string? Notes { get; set; }
    public Guid? CreatedBy { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }

    public QualityRecord? Quality { get; set; }
}

public class QualityRecord
{
    public Guid Id { get; set; }
    public Guid ProductionRecordId { get; set; }
    public ProductionRecord ProductionRecord { get; set; } = null!;
    public int InspectedUnits { get; set; }
    public int RejectedUnits { get; set; }
    public string? DefectType { get; set; }
    public DateTime CreatedAt { get; set; }
}

public class DowntimeEvent : IHasUpdatedAt
{
    public Guid Id { get; set; }
    public Guid EquipmentId { get; set; }
    public Equipment Equipment { get; set; } = null!;
    public DateTime StartTime { get; set; }
    public DateTime EndTime { get; set; }

    /// <summary>Generated by the database from start and end time.</summary>
    public decimal DurationMinutes { get; set; }
    public DowntimeCategory Category { get; set; }
    public string ReasonCode { get; set; } = string.Empty;
    public string? Notes { get; set; }
    public Guid? CreatedBy { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }
}

public class AuditLog
{
    public long Id { get; set; }
    public Guid OrganisationId { get; set; }
    public Guid? UserId { get; set; }
    public string Action { get; set; } = string.Empty;
    public string Entity { get; set; } = string.Empty;
    public string? EntityId { get; set; }
    public string? Details { get; set; }
    public string? IpAddress { get; set; }
    public DateTime CreatedAt { get; set; }
}
